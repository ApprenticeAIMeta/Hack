"""Can a second question catch the locate check's one-step-ahead answers? Writes docs/confirm-test.md.

    python eval/bench_confirm.py     (from backend/, after eval/bench_stills.py)

For each locate answer from bench_stills, asks about the step that answer claims just finished. If the
answer was right the check should say done; if it was ahead the check should say not done.
"""

from __future__ import annotations

import json
import statistics as st
import sys
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from bench_stills import moment, retry  # noqa: E402
from apprentice.guide.policy import SparkPolicy  # noqa: E402
from apprentice.models.meta import MetaClient  # noqa: E402
from apprentice.replay import ROOT  # noqa: E402

PASSES = 2
METHODS = ("confirm", "done")


def main() -> None:
    rows = json.loads((ROOT / "out" / "bench_stills.json").read_text())
    client = MetaClient()
    pol = SparkPolicy(ROOT / "procedures" / "airplane", client)
    claims = sorted({(r["t"], r["truth"], r["n"], r["kind"]) for r in rows if r["n"] >= 1 and r["n"] >= r["truth"] and r["n"] - r["truth"] <= 1})
    with ThreadPoolExecutor(4) as ex:
        ms = {m["t"]: m for m in ex.map(lambda t: moment(client, t), sorted({c[0] for c in claims})) if m}

    def ask(job):
        (t, truth, n, kind), method, p = job
        c = retry(lambda: getattr(pol, method)(n - 1, ms[t][kind]))
        return {"t": t, "truth": truth, "n": n, "kind": kind, "method": method, "p": p, "yes": c.yes, "unclear": c.unclear,
                "conf": c.confidence, "reason": c.reason, "lat": c.latency_s}
    jobs = [(c, m, p) for c in claims if c[0] in ms for m in METHODS for p in range(PASSES)]
    with ThreadPoolExecutor(4) as ex:
        out = list(ex.map(ask, jobs))
    (ROOT / "out" / "bench_confirm.json").write_text(json.dumps(out, indent=1))
    md = ("# Second-question test\n\nGenerated by `backend/eval/bench_confirm.py`: expert1 run, Muse Spark 1.3, "
          f"{PASSES} passes per claim. Right claims should be kept, one-step-ahead claims rejected. Unclear counts as not kept.\n\n"
          "| Check | Image | Right claims kept | Ahead claims rejected | Latency median |\n|---|---|---|---|---|\n")
    for m in METHODS:
        for k in ("still", "stream"):
            x = [r for r in out if r["method"] == m and r["kind"] == k]
            right = [r for r in x if r["n"] == r["truth"]]
            ahead = [r for r in x if r["n"] > r["truth"]]
            kept = sum(r["yes"] and not r["unclear"] for r in right)
            rej = sum(not r["yes"] or r["unclear"] for r in ahead)
            md += f"| {m} | {k} | {kept}/{len(right)} | {rej}/{len(ahead)} | {st.median(r['lat'] for r in x):.1f} s |\n"
    (ROOT / "docs" / "confirm-test.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
