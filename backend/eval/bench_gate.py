"""Would the progress model stop early step advances? Writes docs/progress-gate.md.

    python eval/bench_gate.py     (from backend/, after eval/bench_models.py)

Uses the novice run, the one run the progress model did not train on. First, each stored Muse Spark
locate answer is kept or rejected by progress alone.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_eval import LABELS  # noqa: E402
from apprentice.guide.state import step_ranges  # noqa: E402
from apprentice.progress.align import score  # noqa: E402
from apprentice.progress.model import ProgressModel  # noqa: E402
from apprentice.replay import ROOT  # noqa: E402

GATES = (0.0, 0.05, 0.1, 0.2, 0.3)


def main() -> None:
    lab = json.loads((LABELS / "novice.json").read_text())
    pdir = ROOT / "procedures" / lab["procedure"]
    proc = json.loads((pdir / "procedure.json").read_text())
    video = ROOT / lab["video"]
    s = score(video, "novice", ProgressModel.load(pdir / "progress.npz"), proc["workpiece"])
    ranges = step_ranges(proc)
    ts, ps = np.asarray(s["t"]), np.asarray(s["progress"], float)
    prog = lambda t: float(ps[int(np.argmin(np.abs(ts - t)))])
    rows = json.loads((ROOT / "out" / "bench_models.json").read_text())[0]["rows"]
    claims = [r | {"p": prog(r["t"])} for r in rows if not r["unclear"] and r["n"] >= 1]
    done = [x for x in lab["step_done"] if x is not None]

    md = ("# Progress gate test\n\nGenerated by `backend/eval/bench_gate.py` on the novice run, with stream frames. "
          "Gates were chosen on this one run, so treat the best row as optimistic.\n\n## Progress by labeled step\n\n"
          "| Steps done (label) | Progress median | Min | Max | Expected end of next step |\n|---|---|---|---|---|\n")
    for k in range(len(done) + 1):
        a, b = done[k - 1] if k else -1, done[k] if k < len(done) else lab["end"]
        x = ps[(ts > a) & (ts <= b) & ~np.isnan(ps)]
        if len(x):
            md += f"| {k} | {np.median(x):.2f} | {x.min():.2f} | {x.max():.2f} | {ranges[min(k, len(ranges) - 1)][1]:.2f} |\n"
    md += ("\n## Filtering Muse Spark's answers by progress alone\n\n| Gate | Right kept | One or more ahead rejected | Behind kept |\n|---|---|---|---|\n")
    for g in GATES:
        keep = lambda r: r["p"] >= ranges[r["n"] - 1][1] - g
        right = [r for r in claims if r["n"] == r["truth"]]
        ahead = [r for r in claims if r["n"] > r["truth"]]
        behind = [r for r in claims if r["n"] < r["truth"]]
        md += f"| {g} | {sum(map(keep, right))}/{len(right)} | {sum(not keep(r) for r in ahead)}/{len(ahead)} | {sum(map(keep, behind))}/{len(behind)} |\n"
    md += ("\nOn tracker replay, gates from 0 to 0.3 on every advance changed nothing, because each two-answer advance already "
           "passed. A stricter gate of -0.05 lost step 5, and -0.2 lost steps 4 and 5. So the tracker only gates one-answer advances.\n")
    (ROOT / "docs" / "progress-gate.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
