"""Replay every labeled run and write the eval table to docs/eval.md.

    python eval/run_eval.py            (from backend/)

Labels: eval/labels/*.json, plus out/sessions/*/label.json once its "labeled_by" is filled in
(every recorded live session writes a stub there). Each label has, per step, the time its result
first becomes visible (null if not reached), and mistake windows [{"start", "end", "what"}].
Metrics per run:
  step timing     |tracker step_done time - labeled time|, for steps both reached
  missed / extra  steps labeled done but never confirmed / confirmed but never labeled done
  warnings        true (inside a mistake window, or within 5 s after it starts) vs false
  catch latency   seconds from a mistake's start to its warning
  cost, latency   Spark checks used by the run
Spark answers are cached by the replay, so re-running after tuning the tracker is free.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from apprentice.replay import ROOT, replay  # noqa: E402

LABELS = Path(__file__).resolve().parent / "labels"
GRACE_S = 5.0


def evaluate(label_file: Path) -> dict:
    lab = json.loads(label_file.read_text())
    name = label_file.stem if label_file.parent == LABELS else label_file.parent.name
    r = replay(lab["procedure"], (ROOT / lab["video"]).resolve(), name, end=lab.get("end"))
    done_t: dict[int, float] = {}
    for e in r["events"]:
        if e["kind"] == "step_done":
            done_t.setdefault(e["step"], e["t"])
    errs, missed, extra = [], [], []
    for k, truth in enumerate(lab["step_done"]):
        got = done_t.get(k)
        if truth is not None and got is not None:
            errs.append(got - truth)
        elif truth is not None:
            missed.append(k + 1)
        elif got is not None:
            extra.append(k + 1)
    warns = [e for e in r["events"] if e["kind"] == "warn"]
    caught, false_w, latency = set(), [], []
    for w in warns:
        hit = next((i for i, m in enumerate(lab["mistakes"]) if m["start"] <= w["t"] <= m["end"] + GRACE_S), None)
        if hit is None:
            false_w.append(w["t"])
        elif hit not in caught:
            caught.add(hit)
            latency.append(w["t"] - lab["mistakes"][hit]["start"])
    s = r["summary"]
    return {"run": name, "steps_labeled": sum(x is not None for x in lab["step_done"]),
            "step_errors_s": [round(x, 1) for x in errs],
            "mae_s": round(float(np.mean(np.abs(errs))), 1) if errs else None,
            "median_ae_s": round(float(np.median(np.abs(errs))), 1) if errs else None,
            "missed": missed, "extra": extra,
            "mistakes": len(lab["mistakes"]), "caught": len(caught), "false_warnings": false_w,
            "catch_latency_s": [round(x, 1) for x in latency],
            "checks": s["checks"], "cost_usd": s["check_cost_usd"], "check_latency_s": s["mean_check_latency_s"]}


def table(rows: list[dict]) -> str:
    head = ("| Run | Step timing error (s), per step | Median / mean abs (s) | Missed | Extra | "
            "Mistakes caught | False warnings | Catch latency (s) | Spark checks | Cost | Check latency |\n"
            "|---|---|---|---|---|---|---|---|---|---|---|\n")
    body = ""
    for r in rows:
        body += (f"| {r['run']} | {', '.join(f'{x:+.1f}' for x in r['step_errors_s'])} | {r['median_ae_s']} / {r['mae_s']} | "
                 f"{r['missed'] or '-'} | {r['extra'] or '-'} | {r['caught']}/{r['mistakes']} | {len(r['false_warnings'])} | "
                 f"{', '.join(map(str, r['catch_latency_s'])) or '-'} | {r['checks']} | ${r['cost_usd']:.3f} | {r['check_latency_s']} s |\n")
    return head + body


def main() -> None:
    sessions = [f for f in sorted((ROOT / "out" / "sessions").glob("*/label.json"))
                if json.loads(f.read_text()).get("labeled_by")]
    rows = [evaluate(f) for f in sorted(LABELS.glob("*.json")) + sessions]
    md = ("# Guide eval\n\nGenerated by `backend/eval/run_eval.py` from replays of labeled recordings. "
          "Step timing error is tracker time minus labeled time (negative = early).\n\n" + table(rows))
    out = ROOT / "docs" / "eval.md"
    out.write_text(md)
    print(md)
    print(json.dumps(rows, indent=1))


if __name__ == "__main__":
    main()
